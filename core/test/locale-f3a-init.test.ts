/**
 * RM-061, fatia F3a: a familia init em ingles. Com o locale ingles (`LANG` ou `owner.language`), `ork init`
 * escreve o `orkastery.yaml` com os comentarios em ingles e o bloco do `AGENTS.md` em ingles; o dado (chaves,
 * valores, marcadores) e o mesmo do pt-BR. Negativo: `C.UTF-8`, `es_ES.UTF-8` e `owner.language: pt-BR` com
 * `LANG` ingles saem iguais ao snapshot pt-BR, e o gerador chamado como funcao segue em pt-BR mesmo com o locale
 * ativo em ingles (D2). Os nomes comecam por "locale F3a init:".
 */

import { strict as assert } from 'node:assert';
import { test } from 'node:test';
import * as fs from 'node:fs';
import * as path from 'node:path';
import { ativarLocale } from '../src/locale';
import { manifestoYaml } from '../src/init';
import { blocoAgentsMd, FIM_AGENTS_ORK, INICIO_AGENTS_ORK } from '../src/agents-md';
import { carregarManifesto, LIMITE_MANIFESTO_BYTES } from '../src/manifest';
import { lerYaml } from '../src/yaml';
import { cenario, EN, linhasEmPortugues, ork } from './locale-apoio';
import { DETECCOES, manifestoDoBloco } from './locale-f3a-casos';

const FIXTURE = path.resolve(__dirname, '../../test/fixtures/locale-f3a-pt-BR.json');
const snapshot = (): Record<string, string> => JSON.parse(fs.readFileSync(FIXTURE, 'utf8')) as Record<string, string>;
const C = { LANG: 'C.UTF-8' };
const ES = { LANG: 'es_ES.UTF-8' };
const GITIGNORE_PT_BR = '# Criado pelo ork: esta pasta é da máquina, não do repositório.\n*\n';
const GITIGNORE_EN = '# Created by ork: this folder belongs to the machine, not the repository.\n*\n';

/** O YAML sem as linhas de comentario: o dado que o nucleo le. */
const semComentarios = (yaml: string): string => yaml.split('\n').filter((l) => !/^\s*#/.test(l)).join('\n');
const comentarios = (yaml: string): string => yaml.split('\n').filter((l) => /^\s*#/.test(l)).join('\n');
const ler = (dir: string, arquivo: string): string => fs.readFileSync(path.join(dir, arquivo), 'utf8');

function confereYamlIngles(yaml: string, ptBR: string): void {
  assert.deepEqual(linhasEmPortugues(comentarios(yaml)), [], 'nenhum comentario em pt-BR');
  assert.equal(semComentarios(yaml), semComentarios(ptBR), 'o mesmo dado, linha a linha, sem os comentarios');
  assert.deepEqual(lerYaml(yaml), lerYaml(ptBR), 'o mesmo YAML lido');
  assert.ok(Buffer.byteLength(yaml) < LIMITE_MANIFESTO_BYTES, 'abaixo do limite do manifesto');
  assert.match(yaml, /^# Orkastery manifest \(v1, block B0\)\n# Generated by `ork init`\./);
  assert.match(yaml, /\n {2}# language: en-US {2}# absent: the system locale\n/);
}

/** Sem `package.json`, o `ork init` nao detecta nenhum script de verify. */
const NAO_DETECTADO = /\n {2}# build: not detected\n {2}# test: not detected\n {2}# typecheck: not detected\n/;

function confereAgentsIngles(agents: string): void {
  assert.ok(agents.startsWith(`${INICIO_AGENTS_ORK}\n## Orkastery\n\nProject: **loja** (loj). Base branch: \`main\`.\n`), agents);
  assert.ok(agents.includes('- Start with `ork doctor`, `ork onboarding` and `ork thread status <thread>`.\n'));
  assert.ok(agents.includes('- Respect the thread mode: #Classic, #Maestro, #Auto, #Fast.\n'));
  assert.ok(agents.endsWith(`This block is maintained by \`ork init\`. Edit the rest of the file freely.\n${FIM_AGENTS_ORK}\n`));
  assert.deepEqual(linhasEmPortugues(agents), [], 'nenhuma linha em pt-BR');
}

test('locale F3a init: com LANG ingles, o orkastery.yaml sai com os comentarios em ingles e o mesmo dado; o AGENTS.md, em ingles', () => {
  const c = cenario('f3a-init-en', false);
  try {
    const r = ork(c, EN, false, 'init', '--name', 'loja', '--abbrev', 'loj');
    assert.equal(r.status, 0, r.stderr);
    assert.match(r.stdout, /^Manifest created: /);
    const yaml = ler(c.dir, 'orkastery.yaml');
    confereYamlIngles(yaml, snapshot()['cli: ork init, orkastery.yaml']);
    assert.match(yaml, NAO_DETECTADO);
    const carregado = carregarManifesto(c.dir);
    assert.ok(carregado && carregado.erros.length === 0, 'o manifesto em ingles carrega sem erro');
    confereAgentsIngles(ler(c.dir, 'AGENTS.md'));
    assert.equal(ler(c.dir, '.orkastery/.gitignore'), GITIGNORE_EN);
  } finally { c.limpar(); }
});

test('locale F3a init: owner.language en-US vence o ambiente no init --force, e o AGENTS.md sai na mesma lingua do YAML regravado', () => {
  const c = cenario('f3a-init-owner', false);
  try {
    assert.equal(ork(c, C, false, 'init', '--name', 'loja', '--abbrev', 'loj').status, 0);
    const yaml = path.join(c.dir, 'orkastery.yaml');
    fs.writeFileSync(yaml, ler(c.dir, 'orkastery.yaml').replace('  # language: pt-BR  # ausente: locale do sistema', '  language: en-US'));
    const r = ork(c, C, false, 'init', '--force', '--name', 'loja', '--abbrev', 'loj');
    assert.equal(r.status, 0, r.stderr);
    assert.match(r.stdout, /^Manifest created: /);
    // O YAML regravado volta ao modelo (sem owner.language), e mesmo assim o AGENTS.md segue a lingua do comando.
    confereYamlIngles(ler(c.dir, 'orkastery.yaml'), snapshot()['cli: ork init, orkastery.yaml']);
    assert.match(ler(c.dir, 'orkastery.yaml'), NAO_DETECTADO);
    confereAgentsIngles(ler(c.dir, 'AGENTS.md'));
  } finally { c.limpar(); }
});

test('locale F3a init (negativo): C.UTF-8, es_ES.UTF-8 e owner.language pt-BR com LANG ingles saem iguais ao snapshot pt-BR', () => {
  const s = snapshot();
  for (const [nome, locale] of [['C', C], ['es', ES]] as const) {
    const c = cenario(`f3a-init-${nome}`, false);
    try {
      assert.equal(ork(c, locale, false, 'init', '--name', 'loja', '--abbrev', 'loj').status, 0, nome);
      assert.equal(ler(c.dir, 'orkastery.yaml'), s['cli: ork init, orkastery.yaml'], `${nome}: yaml`);
      assert.equal(ler(c.dir, 'AGENTS.md'), s['cli: ork init, AGENTS.md'], `${nome}: AGENTS.md`);
      assert.equal(ler(c.dir, '.orkastery/.gitignore'), GITIGNORE_PT_BR, `${nome}: gitignore`);
    } finally { c.limpar(); }
  }
  const c = cenario('f3a-init-pt-owner', false);
  try {
    assert.equal(ork(c, EN, false, 'init', '--name', 'loja', '--abbrev', 'loj').status, 0);
    const yaml = path.join(c.dir, 'orkastery.yaml');
    fs.writeFileSync(yaml, ler(c.dir, 'orkastery.yaml').replace('  # language: en-US  # absent: the system locale', '  language: pt-BR'));
    const r = ork(c, EN, false, 'init', '--force', '--name', 'loja', '--abbrev', 'loj');
    assert.equal(r.status, 0, r.stderr);
    assert.match(r.stdout, /^Manifesto criado: /);
    assert.equal(ler(c.dir, 'orkastery.yaml'), s['cli: ork init, orkastery.yaml']);
    assert.equal(ler(c.dir, 'AGENTS.md'), s['cli: ork init, AGENTS.md']);
    assert.equal(ler(c.dir, '.orkastery/.gitignore'), GITIGNORE_PT_BR);
  } finally { c.limpar(); }
});

test('locale F3a init (negativo): o gerador chamado como funcao segue em pt-BR com o locale ativo em ingles', () => {
  const s = snapshot();
  ativarLocale('en');
  try {
    for (const [nome, d] of Object.entries(DETECCOES)) assert.equal(manifestoYaml(d), s[`yaml: deteccao ${nome}`], nome);
    assert.equal(blocoAgentsMd(manifestoDoBloco({})), s['agents.md: bloco sem verificacoes']);
    // Pedido explicito, o ingles: o mesmo dado das tres deteccoes.
    for (const [nome, d] of Object.entries(DETECCOES)) confereYamlIngles(manifestoYaml(d, 'en'), s[`yaml: deteccao ${nome}`]);
  } finally { ativarLocale(undefined); }
});

test('locale F3a init: com --json o texto impresso sai do locale, mas os arquivos seguem a lingua do dono (W3 do CHECK)', () => {
  const c = cenario('f3a-init-json', false);
  try {
    const r = ork(c, EN, false, 'init', '--json', '--name', 'loja', '--abbrev', 'loj');
    assert.equal(r.status, 0, r.stderr);
    confereYamlIngles(ler(c.dir, 'orkastery.yaml'), snapshot()['cli: ork init, orkastery.yaml']);
    confereAgentsIngles(ler(c.dir, 'AGENTS.md'));
    assert.equal(ler(c.dir, '.orkastery/.gitignore'), GITIGNORE_EN);
  } finally { c.limpar(); }
});

test('locale F3a init: com LANG ingles, os marcadores repetidos no AGENTS.md recusam em ingles, sem escrever', () => {
  const c = cenario('f3a-init-marcadores', false);
  try {
    const antes = `${INICIO_AGENTS_ORK}\n${INICIO_AGENTS_ORK}\n${FIM_AGENTS_ORK}\n`;
    fs.writeFileSync(path.join(c.dir, 'AGENTS.md'), antes);
    const r = ork(c, EN, false, 'init', '--name', 'loja', '--abbrev', 'loj');
    assert.equal(r.status, 1);
    assert.equal(r.stderr, 'error: AGENTS.md has ambiguous Orkastery markers; fix the block before you run `ork init`.\n');
    assert.equal(ler(c.dir, 'AGENTS.md'), antes);
  } finally { c.limpar(); }
});
